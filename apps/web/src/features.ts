// feature flag の読み出しはここ1か所だけ（ADR-024 決定2 / B-10 設計 規則1）。
//
// 有効になるのは値が文字列 'true' と厳密一致するときだけで、大文字小文字も前後の空白も
// 吸収しない（ADR-024 決定1）。未指定・空文字列・'1'・'TRUE' はすべて無効に倒れる —
// 指定を忘れた環境が「未完成が見えている」側に倒れないため（同 結果4）。
//
// 値はこのモジュールの読み込み時に1度だけ決まり、以後変わらない。実行時に切り替える
// 手段は置かない（同 結果3）。切り替えには再ビルドが要る。
//
// 最初の消費者（B-11）で実測した結果、**無効側の分岐は成果物から落ちない。**
// import.meta.env.VITE_FEATURE_* の定数への置き換えは効く（バンドルに pantryList:!1 と
// 出る）が、features オブジェクトのプロパティ読みを越えた定数伝播は行われず、
// 分岐の両側が配信物に残る。フラグは表示の可否を決めるという役目を果たすものの
// （ADR-024 決定3）、未完成のコードが配信物に載ることは引き受けている（同 結果1）。
// 落とすかどうかは features.ts の形に関わる設計の決定であり、backlog B-21 で扱う。
export const features = {
  pantryList: import.meta.env.VITE_FEATURE_PANTRY_LIST === 'true',
} as const;
